const CAPC = {
  say: { bg: '#FFFBF0', bd: PAL.ink, fs: 42 }, we: { bg: '#F0FAF8', bd: '#3A9C98', fs: 42 },
  clawd: { bg: '#FFF4EE', bd: PAL.clayDk, fs: 42 }, key: { bg: '#FFE9AE', bd: PAL.ink, fs: 50 },
};
const CAP_FONT = (px) => `bold ${px}px "Microsoft YaHei", "微软雅黑", "PingFang SC", sans-serif`;
let _mctx = null;
const textW = (s, px) => { if (!_mctx) _mctx = document.createElement('canvas').getContext('2d'); _mctx.font = CAP_FONT(px); return _mctx.measureText(s).width; };
// 把"……「上下文」……"拆成普通段和高亮段
const capRuns = s => s.split(/(「[^」]*」)/).filter(Boolean).map(x => x.startsWith('「') ? { s: x.slice(1, -1), hi: true } : { s: x, hi: false });

function drawCaptions(t) {
  const active = CAPS.filter(c => t >= c[0] - .02 && t < c[1]);
  active.forEach((c, i) => drawBubble(c, t, i));
}
function drawBubble([t0, t1, kind, text, anchor, o = {}], t, idx) {
  const C = CAPC[kind] || CAPC.say, fs = C.fs, a = t - t0, b = t1 - t;
  const k = a < .18 ? backOut(a / .18) : b < .2 ? .85 + .15 * (b / .2) : 1, alpha = b < .2 ? b / .2 : 1;
  if (k <= .02) return;
  const runs = capRuns(text), tw = runs.reduce((s, r) => s + textW(r.s, fs), 0);
  const padX = 28, padY = 18, icon = kind === 'we' ? 40 : 0;
  const w = tw + padX * 2 + icon, h = fs + padY * 2;
  // 指向点（屏幕坐标）
  let A = null;
  if (anchor) { const p = typeof anchor === 'function' ? anchor(t) : anchor; A = p.s ? p.s : toScreen(p[0], p[1], LAST_CAM); }
  // 气泡中心
  let cx, cy;
  if (o.at) [cx, cy] = o.at;
  else if (!A) { cx = W / 2; cy = H - 96 - idx * (h + 16); }
  else {
    const side = o.side || 'up', gap = 46;
    cx = side === 'left' ? A[0] - w / 2 - gap : side === 'right' ? A[0] + w / 2 + gap : A[0];
    cy = side === 'up' ? A[1] - h / 2 - gap : side === 'down' ? A[1] + h / 2 + gap : A[1];
  }
  cx += o.dx || 0; cy += o.dy || 0;
  cx = clamp(cx, w / 2 + 30, W - w / 2 - 30); cy = clamp(cy, h / 2 + 24, H - h / 2 - 24);
  boilSeed('cap' + t0);
  push(); translate(cx, cy); scale(k);
  // 尖角：从气泡中心往指向点画一个三角（停在指向点前一点），气泡本体压在上面
  if (A) {
    const dx = A[0] - cx, dy = A[1] - cy, d = Math.hypot(dx, dy) || 1, ux = dx / d, uy = dy / d, base = Math.min(w, h) * .2;
    const tip = [(d - 12) * ux / k, (d - 12) * uy / k];
    paint([[-uy * base, ux * base], tip, [uy * base, -ux * base]], { wash: C.bg, ink: C.bd, sw: 1.1 });
  }
  paint(rrPts(-w / 2, -h / 2, w, h, h * .32), { wash: C.bg, ink: C.bd, sw: kind === 'say' ? 1.1 : 1.8 });
  pop();
  if (kind === 'we') cursorHand(cx - w / 2 * k + (padX + 12) * k, cy - 4 * k, 1.6 * k, { key: 'capcursor' + t0 });
  // 文字：一段段排开，高亮段用醒目的颜色
  let x = cx - w / 2 * k + (padX + icon) * k;
  for (const r of runs) {
    const rw = textW(r.s, fs) * k;
    letter(r.s, x, cy + 2 * k, fs * k, r.hi ? '#C2410C' : PAL.ink, { screen: true, ink: false, align: 'left', alpha, font: CAP_FONT(fs * k) });
    x += rw;
  }
}
